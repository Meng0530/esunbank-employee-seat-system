USE [EmployeeSeatDB]
GO

CREATE TABLE SEATING_CHART (
    FLOOR_SEAT_SEQ INT PRIMARY KEY,
    FLOOR_NO INT NOT NULL,
    SEAT_NO INT NOT NULL,
    CONSTRAINT UK_FLOOR_SEAT UNIQUE (FLOOR_NO, SEAT_NO)
);

CREATE TABLE EMPLOYEE (
    EMP_ID VARCHAR(5) PRIMARY KEY,
    NAME VARCHAR(50) NOT NULL,
    EMAIL VARCHAR(100),
    FLOOR_SEAT_SEQ INT,
    CONSTRAINT FK_EMP_SEAT FOREIGN KEY (FLOOR_SEAT_SEQ) REFERENCES SEATING_CHART(FLOOR_SEAT_SEQ),
    CONSTRAINT UK_EMP_SEAT UNIQUE (FLOOR_SEAT_SEQ)
);

CREATE TABLE SEAT_CHANGE_LOG (
    LOG_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMP_ID VARCHAR(5) NOT NULL,
    OLD_SEAT_SEQ INT,
    NEW_SEAT_SEQ INT,
    CHANGE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
